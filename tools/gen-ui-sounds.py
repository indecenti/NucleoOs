#!/usr/bin/env python3
"""The Games gallery's interface sounds, as 16 kHz mono PCM in the firmware (gamefront.cpp plays them).

    python tools/gen-ui-sounds.py        writes firmware/components/nucleo_app/gamefront_sfx.h

Source: Kenney "Interface Sounds" (CC0), already in assets/audio/interface-sounds/Audio. Each sound is decoded with
ffmpeg, its silence trimmed, cut to a maximum length with a short fade-out (no click at the end), and kept as int16
at full scale: the firmware plays it at a fraction of the software volume (nucleo_audio_sample).
"""
import os
import struct
import subprocess

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SRC = os.path.join(ROOT, "assets", "audio", "interface-sounds", "Audio")
OUT = os.path.join(ROOT, "firmware", "components", "nucleo_app", "gamefront_sfx.h")
RATE = 16000
# name in the firmware, Kenney file, longest it may last (ms). The wheel's own tick is a 4 ms tone, as in the
# emulators' shelf (nucleo_audio_tone): a sample would hold every step longer.
SOUNDS = [
    ("OPEN",   "pluck_001.ogg",        70),    # into a system
    ("BACK",   "back_001.ogg",         60),    # back a level / out
    ("LAUNCH", "confirmation_001.ogg", 220),   # a game starts
]


def pcm(path, max_ms):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", path, "-ac", "1", "-ar", str(RATE), "-f", "s16le", "-"],
                         capture_output=True, check=True).stdout
    s = list(struct.unpack("<%dh" % (len(raw) // 2), raw))
    peak = max(abs(x) for x in s) or 1
    th = peak * 0.02
    a = next(i for i, x in enumerate(s) if abs(x) > th)
    b = len(s) - next(i for i, x in enumerate(reversed(s)) if abs(x) > th)
    s = s[a:min(b, a + RATE * max_ms // 1000)]
    fade = min(len(s), RATE * 6 // 1000)                       # 6 ms out
    for i in range(fade):
        s[len(s) - fade + i] = s[len(s) - fade + i] * (fade - i) // fade
    k = 30000 / peak                                           # full scale: the player sets the level
    return [max(-32767, min(32767, int(x * k))) for x in s]


def main():
    lines = ["// Generated by tools/gen-ui-sounds.py - do not edit. Kenney \"Interface Sounds\", CC0 (public domain).",
             "// 16 kHz mono int16 PCM at full scale; gamefront.cpp plays them with nucleo_audio_sample().",
             "#pragma once", "#include <stdint.h>", ""]
    total = 0
    for name, file, ms in SOUNDS:
        s = pcm(os.path.join(SRC, file), ms)
        total += len(s) * 2
        lines.append(f"static const int16_t SFX_{name}[{len(s)}] = {{   // {file}, {len(s) * 1000 // RATE} ms")
        for i in range(0, len(s), 16):
            lines.append("    " + ",".join(str(x) for x in s[i:i + 16]) + ",")
        lines.append("};")
    lines.append("")
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"gen-ui-sounds: {len(SOUNDS)} sounds, {total} B -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
