#!/usr/bin/env python3
"""Console pictures for the emulators' gallery (app_gbemu.cpp, second screen).

    python tools/gen-emu-art.py <gb.jpg> <gg.jpg> <sms.jpg>

The photos are Evan-Amos's public-domain shots on Wikimedia Commons (Game-Boy-FL.jpg, Game-Gear-Handheld.jpg,
Sega-Master-System-Console-FL.jpg). Each is trimmed to the console, its white studio background is turned into the light
tile colour the gallery draws behind it, scaled to fit the picture box, and written twice:

  firmware/components/nucleo_app/gbemu_art/<id>.png   the reviewable image (what the panel shows)
  firmware/components/nucleo_app/gbemu_art.h          RGB565 (native byte order, what pushImage takes), raw
                                                       deflate: the module inflates it with the ROM's tinfl
"""
import os
import sys
import zlib
from collections import deque

from PIL import Image, ImageFilter

BOX_W, BOX_H = 120, 80                # the picture box on the gallery's left (app_gbemu.cpp)
TILE = (0xE6, 0xE8, 0xEC)             # the tile behind the picture (ART_TILE in the header, as RGB565)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "firmware", "components", "nucleo_app")


def tile_background(img):
    """Flood-fill the near-white studio background from the borders into the tile colour."""
    img = img.convert("RGB")
    w, h = img.size
    px = img.load()
    seen = bytearray(w * h)
    q = deque((x, y) for x in range(w) for y in (0, h - 1))
    q.extend((x, y) for y in range(h) for x in (0, w - 1))
    while q:
        x, y = q.popleft()
        if x < 0 or y < 0 or x >= w or y >= h or seen[y * w + x]:
            continue
        seen[y * w + x] = 1
        r, g, b = px[x, y]
        if min(r, g, b) < 225:
            continue
        px[x, y] = TILE
        q.extend(((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)))
    return img


def trim(img):
    """Cut the studio white around the console (plus a 2 % margin), so it fills the thumbnail box."""
    img = img.convert("RGB")
    mask = img.convert("L").point(lambda v: 255 if v < 235 else 0)
    l, t, r, b = mask.getbbox()
    m = max(r - l, b - t) // 50
    return img.crop((max(0, l - m), max(0, t - m), min(img.width, r + m), min(img.height, b + m)))


def thumb(path):
    img = tile_background(trim(Image.open(path)))
    img.thumbnail((BOX_W, BOX_H), Image.LANCZOS)
    return img.filter(ImageFilter.UnsharpMask(radius=0.6, percent=60, threshold=2))


def rgb565(img):
    out = bytearray()
    for r, g, b in img.get_flattened_data() if hasattr(img, "get_flattened_data") else img.getdata():
        v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        out += bytes((v & 0xFF, v >> 8))       # little endian: the uint16_t the CPU reads
    return bytes(out)


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    os.makedirs(os.path.join(OUT, "gbemu_art"), exist_ok=True)
    lines = ["// Generated by tools/gen-emu-art.py - do not edit. Console photos: Evan-Amos, public domain",
             "// (Wikimedia Commons). RGB565 in native byte order, raw deflate (inflate with tinfl, no zlib header).",
             "#pragma once", "#include <stdint.h>", "",
             f"#define ART_TILE 0x{((TILE[0] & 0xF8) << 8) | ((TILE[1] & 0xFC) << 3) | (TILE[2] >> 3):04X}", ""]
    for key, path in zip(("gb", "gg", "sms"), sys.argv[1:]):
        img = thumb(path)
        img.save(os.path.join(OUT, "gbemu_art", f"{key}.png"), optimize=True)
        raw = rgb565(img)
        c = zlib.compressobj(9, zlib.DEFLATED, -15, 9)
        z = c.compress(raw) + c.flush()
        w, h = img.size
        body = ",".join(str(b) for b in z)
        lines += [f"static const uint8_t ART_{key.upper()}_Z[{len(z)}] = {{{body}}};",
                  f"#define ART_{key.upper()}_W {w}", f"#define ART_{key.upper()}_H {h}", ""]
        print(f"{key}: {w}x{h}, {len(raw)} B -> {len(z)} B deflated")
    with open(os.path.join(OUT, "gbemu_art.h"), "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
