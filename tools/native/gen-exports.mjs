#!/usr/bin/env node
// Generates the firmware's native-app ABI export table from sdk/native/abi/v<N>.txt.
//   node tools/native/gen-exports.mjs           write firmware/components/nucleo_app/nap_exports.S
//   node tools/native/gen-exports.mjs --check   exit 1 when the committed file differs (native:test runs it)
//
// The table is assembly on purpose: a C file would have to declare every import (memcpy as a char array,
// mangled C++ names...) and fight the compiler's built-in prototypes. Here every entry is just
// `.word <name string>, <symbol>`: the linker resolves the symbol, and a name the firmware does not have
// fails the firmware build instead of failing an app on a user's device.
// Levels only grow: level N's file must contain every name of level N-1 (checked here).
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const ABI = join(root, 'sdk', 'native', 'abi');
const OUT = join(root, 'firmware', 'components', 'nucleo_app', 'nap_exports.S');
const NAME_RE = /^[A-Za-z_][A-Za-z0-9_.$]*$/;

function parse(file) {
  const out = new Map();
  readFileSync(file, 'utf8').split(/\r?\n/).forEach((raw, i) => {
    const line = raw.replace(/#.*/, '').trim();
    if (!line) return;
    const m = line.match(/^(\S+)(?:\s*=\s*(\S+))?$/);
    if (!m || !NAME_RE.test(m[1]) || (m[2] && !NAME_RE.test(m[2]))) throw new Error(`${file}:${i + 1}: bad line '${raw}'`);
    if (out.has(m[1])) throw new Error(`${file}:${i + 1}: '${m[1]}' listed twice`);
    out.set(m[1], m[2] || m[1]);
  });
  return out;
}

const levels = readdirSync(ABI).map((f) => f.match(/^v(\d+)\.txt$/)).filter(Boolean).map((m) => +m[1]).sort((a, b) => a - b);
if (!levels.length || levels[0] !== 1 || levels.some((v, i) => v !== i + 1)) throw new Error('abi/: need v1.txt, v2.txt, ... with no gaps');
let prev = null;
let all = null;
for (const v of levels) {
  const cur = parse(join(ABI, `v${v}.txt`));
  if (prev) for (const [k, t] of prev) {
    if (!cur.has(k)) throw new Error(`abi/v${v}.txt drops '${k}' from v${v - 1}: a level only grows`);
    if (cur.get(k) !== t) throw new Error(`abi/v${v}.txt reroutes '${k}': an export keeps its target`);
  }
  prev = all = cur;
}
const max = levels[levels.length - 1];
// strcmp order = byte order of ASCII names: the loader binary-searches it.
const names = [...all.keys()].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

const lines = [
  '// GENERATED by tools/native/gen-exports.mjs from sdk/native/abi/v*.txt - do not edit.',
  '// The native-app ABI export table: { const char *name; uint32_t addr; } sorted by name (nap_loader.c',
  '// binary-searches it). See docs/native-apps.md.',
  '    .section .rodata.nap_exports, "a"',
  '    .align 4',
  '    .global nap_abi_level',
  'nap_abi_level:',
  `    .word ${max}`,
  '    .global nap_exports_count',
  'nap_exports_count:',
  `    .word ${names.length}`,
  '    .global nap_exports',
  'nap_exports:',
  ...names.map((n, i) => `    .word .Lnap_n${i}, ${all.get(n)}`),
  '',
  '    .section .rodata.nap_export_names, "aMS", @progbits, 1',
  ...names.map((n, i) => `.Lnap_n${i}: .asciz "${n}"`),
  '',
];
const text = lines.join('\n');
if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) {
    console.error('native: nap_exports.S is out of date - run: node tools/native/gen-exports.mjs');
    process.exit(1);
  }
  console.log(`native: export table up to date (ABI ${max}, ${names.length} names)`);
} else {
  writeFileSync(OUT, text);
  console.log(`native: wrote ${OUT} (ABI ${max}, ${names.length} names)`);
}
